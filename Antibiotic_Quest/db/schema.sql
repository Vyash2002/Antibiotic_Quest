-- Antibiotic Quest - SQLite schema
-- Anonymous by design: no names, phone numbers, emails or patient information.

PRAGMA foreign_keys = ON;

-- Verified source facts (loaded from data/AMR_Facts.csv)
CREATE TABLE IF NOT EXISTS facts (
    fact_id       TEXT PRIMARY KEY,
    topic         TEXT NOT NULL,
    statement     TEXT NOT NULL,
    source_org    TEXT NOT NULL,
    source_url    TEXT NOT NULL,
    use_in_game   TEXT NOT NULL CHECK (use_in_game IN ('yes', 'background'))
);

-- In-game questions (loaded from data/AMR_Question_Bank.csv, plus LLM drafts)
CREATE TABLE IF NOT EXISTS questions (
    question_id    TEXT PRIMARY KEY,
    level          INTEGER NOT NULL CHECK (level BETWEEN 1 AND 5),
    topic          TEXT NOT NULL,
    difficulty     TEXT NOT NULL CHECK (difficulty IN ('easy', 'medium', 'hard')),
    question_type  TEXT NOT NULL CHECK (question_type IN ('tf', 'mcq', 'scenario')),
    question_en TEXT NOT NULL, option_a_en TEXT, option_b_en TEXT, option_c_en TEXT, option_d_en TEXT,
    explanation_en TEXT NOT NULL, hint_en TEXT,
    question_hi TEXT, option_a_hi TEXT, option_b_hi TEXT, option_c_hi TEXT, option_d_hi TEXT,
    explanation_hi TEXT, hint_hi TEXT,
    correct_answer TEXT NOT NULL CHECK (correct_answer IN ('A', 'B', 'C', 'D')),
    fact_ids       TEXT NOT NULL,            -- ';'-separated Fact_IDs
    drafted_by     TEXT,
    review_status  TEXT NOT NULL DEFAULT 'pending_review'
                   CHECK (review_status IN ('pending_review', 'approved', 'needs_edit', 'rejected')),
    reviewer       TEXT,
    review_date    TEXT,
    review_notes   TEXT
);

-- Only approved questions are ever served to players
CREATE VIEW IF NOT EXISTS playable_questions AS
    SELECT * FROM questions WHERE review_status = 'approved';

-- One row per anonymous participant. is_synthetic = 1 marks team test runs / synthetic data;
-- exports leave them out unless asked.
CREATE TABLE IF NOT EXISTS participants (
    participant_id     TEXT PRIMARY KEY,          -- P001, P002 ... generated by the server
    consent_given      INTEGER NOT NULL CHECK (consent_given IN (0, 1)),
    consent_timestamp  TEXT NOT NULL,
    age_band TEXT, gender TEXT, background TEXT, prior_amr_teaching TEXT,
    language           TEXT NOT NULL DEFAULT 'en' CHECK (language IN ('en', 'hi')),
    is_synthetic       INTEGER NOT NULL DEFAULT 0
);

-- Pre/post test responses, item level (items from data/Pre_Post_Test_Instrument.csv)
CREATE TABLE IF NOT EXISTS test_responses (
    participant_id  TEXT NOT NULL REFERENCES participants(participant_id),
    phase           TEXT NOT NULL CHECK (phase IN ('pre', 'post')),
    item_id         TEXT NOT NULL,               -- K01..K16, A01..A06, FB01..FB05
    response        TEXT,                        -- 'True'/'False'/"Don't know", 'A'-'D', '1'-'5' or free text
    answered_at     TEXT NOT NULL,
    PRIMARY KEY (participant_id, phase, item_id)
);

CREATE TABLE IF NOT EXISTS game_sessions (
    session_id      TEXT PRIMARY KEY,
    participant_id  TEXT NOT NULL REFERENCES participants(participant_id),
    started_at      TEXT NOT NULL,
    ended_at        TEXT,
    language        TEXT NOT NULL,
    audio_enabled   INTEGER NOT NULL DEFAULT 0
);

-- Every answer the player gives inside the game
CREATE TABLE IF NOT EXISTS answer_events (
    event_id          INTEGER PRIMARY KEY AUTOINCREMENT,
    session_id        TEXT NOT NULL REFERENCES game_sessions(session_id),
    participant_id    TEXT NOT NULL REFERENCES participants(participant_id),
    level             INTEGER NOT NULL,
    question_id       TEXT NOT NULL REFERENCES questions(question_id),
    language          TEXT NOT NULL,
    attempt_no        INTEGER NOT NULL DEFAULT 1,
    selected_option   TEXT NOT NULL,
    correct_option    TEXT NOT NULL,
    is_correct        INTEGER NOT NULL CHECK (is_correct IN (0, 1)),
    hint_used         INTEGER NOT NULL DEFAULT 0,
    audio_played      INTEGER NOT NULL DEFAULT 0,
    response_time_ms  INTEGER,
    points_awarded    INTEGER NOT NULL DEFAULT 0,
    timestamp         TEXT NOT NULL
);

-- Level start/finish markers. question_ids = the questions served for this level (';'-separated)
CREATE TABLE IF NOT EXISTS level_progress (
    session_id      TEXT NOT NULL REFERENCES game_sessions(session_id),
    level           INTEGER NOT NULL,
    started_at      TEXT NOT NULL,
    ended_at        TEXT,
    level_completed INTEGER NOT NULL DEFAULT 0,
    question_ids    TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (session_id, level)
);

-- Log of AI question-drafting runs (for the "LLM drafts approved" metric)
CREATE TABLE IF NOT EXISTS llm_runs (
    run_id          INTEGER PRIMARY KEY AUTOINCREMENT,
    created_at      TEXT NOT NULL,
    model           TEXT NOT NULL,
    level           INTEGER NOT NULL,
    difficulty      TEXT NOT NULL,
    n_requested     INTEGER NOT NULL,
    n_returned      INTEGER NOT NULL DEFAULT 0,
    n_failed_checks INTEGER NOT NULL DEFAULT 0,
    n_inserted      INTEGER NOT NULL DEFAULT 0,
    error           TEXT
);

-- Level summary = Dataset 3 in the project plan
CREATE VIEW IF NOT EXISTS gameplay_analytics AS
SELECT  s.participant_id,
        lp.session_id,
        p.is_synthetic,
        lp.level,
        COUNT(e.event_id)                                   AS questions_attempted,
        COALESCE(SUM(e.is_correct), 0)                      AS correct,
        COUNT(e.event_id) - COALESCE(SUM(e.is_correct), 0)  AS incorrect,
        COALESCE(SUM(e.hint_used), 0)                       AS hints_used,
        CAST(ROUND((julianday(COALESCE(lp.ended_at, MAX(e.timestamp), lp.started_at))
                    - julianday(lp.started_at)) * 86400) AS INTEGER) AS time_spent_sec,
        COALESCE(SUM(e.points_awarded), 0)                  AS points,
        lp.level_completed,
        COALESCE(MAX(e.audio_played), 0)                    AS audio_used,
        s.language,
        lp.started_at,
        lp.ended_at
FROM level_progress lp
JOIN game_sessions s ON s.session_id = lp.session_id
JOIN participants p ON p.participant_id = s.participant_id
LEFT JOIN answer_events e ON e.session_id = lp.session_id AND e.level = lp.level
GROUP BY lp.session_id, lp.level;
